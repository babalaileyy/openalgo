/** Indicator legends often append parameters to the registered name. */
export function indicatorInstanceName(name: string): string {
  for (const original of Object.keys(names).sort((a, b) => b.length - a.length)) {
    if (name === original || name.startsWith(`${original} `)) {
      return `${indicatorName(original)}${name.slice(original.length)}`
    }
  }
  return name
}
